package com.tagback.service;

import com.tagback.domain.entity.Item;
import com.tagback.domain.entity.ItemStatus;
import com.tagback.domain.repository.ItemRepository;
import com.tagback.domain.repository.ItemTypeRepository;
import com.tagback.dto.item.ItemRequests;
import com.tagback.dto.item.ItemResponses;
import com.tagback.exception.ItemException;
import com.tagback.exception.AuthException;
import com.tagback.exception.AuthErrorCode;
import jakarta.persistence.EntityManager;
import java.util.Set;
import org.hibernate.exception.ConstraintViolationException;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class ItemService {
    private final ItemRepository items;
    private final ItemTypeRepository types;
    private final EntityManager entityManager;

    public ItemService(ItemRepository items, ItemTypeRepository types, EntityManager entityManager) {
        this.items = items;
        this.types = types;
        this.entityManager = entityManager;
    }

    @Transactional
    public ItemResponses.Detail create(ItemRequests.Create request) {
        var type = types.findById(Long.parseLong(request.itemTypeId())).orElseThrow(ItemException::new);
        var item = items.saveAndFlush(new Item(request.itemName(), ItemStatus.TAG_PENDING, type));
        // created_at is generated by PostgreSQL, so reload before returning it.
        entityManager.refresh(item);
        return ItemResponses.Detail.from(item);
    }

    @Transactional(readOnly = true)
    public ItemResponses.Detail detail(long itemId) {
        return ItemResponses.Detail.from(items.findById(itemId).orElseThrow(ItemException::itemNotFound));
    }

    @Transactional
    public ItemResponses.Detail update(long itemId, ItemRequests.Update request) {
        var item = items.findForUpdate(itemId).orElseThrow(ItemException::itemNotFound);
        var type = item.getItemType();
        if (request.getItemTypeId() != null) {
            long typeId = Long.parseLong(request.getItemTypeId());
            if (typeId != type.getId()) {
                type = types.findById(typeId).orElseThrow(ItemException::new);
                if (items.hasUsageHistory(itemId)) throw ItemException.typeChangeConflict();
            }
        }
        item.updateDetails(request.getItemName() == null ? item.getItemName() : request.getItemName(), type);
        items.flush();
        return ItemResponses.Detail.from(item);
    }

    @Transactional(readOnly = true)
    public ItemResponses.ItemPage list(int page, int size, Long itemTypeId, ItemStatus status) {
        // JPA setFirstResult only accepts an int even though PageRequest uses a long offset.
        if (page < 0 || size < 1 || size > 100 || (long) page * size > Integer.MAX_VALUE) {
            throw new AuthException(AuthErrorCode.INVALID_INPUT);
        }
        var result = items.findFiltered(itemTypeId, status,
                PageRequest.of(page, size, Sort.by(Sort.Direction.DESC, "id")));
        return new ItemResponses.ItemPage(result.getContent().stream().map(ItemResponses.Detail::from).toList(),
                page, size, result.getTotalElements(), result.getTotalPages());
    }

    @Transactional
    public void delete(long itemId) {
        var item = items.findForUpdate(itemId).orElseThrow(ItemException::itemNotFound);
        if (items.hasDeletionReferences(itemId)) throw ItemException.deleteConflict();
        try {
            items.delete(item);
            // Flush here so FK errors are handled before returning a success response.
            items.flush();
        } catch (DataIntegrityViolationException exception) {
            if (isItemReferenceViolation(exception)) throw ItemException.deleteConflict();
            throw exception;
        }
    }

    private boolean isItemReferenceViolation(Throwable exception) {
        var constraints = Set.of("fk_nfc_tags_item", "fk_rentals_item", "fk_inspections_item");
        for (Throwable cause = exception; cause != null; cause = cause.getCause()) {
            if (cause instanceof ConstraintViolationException violation
                    && "23503".equals(violation.getSQLState())
                    && violation.getConstraintName() != null
                    && constraints.contains(violation.getConstraintName())) return true;
        }
        return false;
    }

}
